"""Build RAFT's MuJoCo and URDF packages from source/raft and the shared palette.

source/raft/reference.json is RAFT's model reference: frames, mass properties, ranges, keyframes and actuation,
exported by RAFT's firmware generator (tools/import_raft_reference.py imports it with the CAD meshes and their
visual pieces). Colours come from source/appearance/colors.json (raft_* keys; the servos follow `motors`, or the
`raft_motors` override). Both packages are rewritten completely. The shared build steps then add ROS 2 support
(build_ros_support.py), the licences and the documentation index (package_models.py).
"""
import json
from pathlib import Path
import re
import shutil
import xml.etree.ElementTree as ET

import sys

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))   # isolated (-I) mode, or called from elsewhere
from model_colors import color, load as load_palette, rgba

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT/'source/raft'
MUJOCO = ROOT/'mujoco/raft'
URDF = ROOT/'urdf/raft_description'
# visual piece -> palette part; the trigger's printed part has its own key
PIECE_COLOR = {'structure': 'raft_structure', 'trigger': 'raft_trigger', 'motors': 'raft_motors',
               'horns': 'raft_horns', 'fasteners': 'raft_fasteners'}
SHINE = {'structure': (.25, .35), 'trigger': (.25, .35), 'motors': (.3, .25), 'horns': (.9, .9), 'fasteners': (.8, .8)}
# PAR6's lengths in the kinematic review (docs/kinematics), the SSG48/MSG tool point for a6
PAR6_MM = {'a2': 23.420721, 'a3': 180.0, 'a4': 43.5, 'a5': 177.0, 'a6 (TCP)': 140.9}


def version():
    return ET.parse(ROOT/'urdf/par6_description/package.xml').findtext('version')


def reference():
    data = json.loads((SOURCE/'reference.json').read_text(encoding='utf-8'))
    if data.get('schema_version') != 1 or data.get('robot') != 'raft':
        raise ValueError('source/raft/reference.json: expected a RAFT model reference, schema version 1')
    return data


def partitions():
    return json.loads((SOURCE/'visual/partitions.json').read_text(encoding='utf-8'))


def fmt(values):
    return ' '.join(f'{0.0 if abs(x) < 1e-15 else x:.12g}' for x in values)


def piece_key(link, piece):
    return 'trigger' if (link == 'trigger_link' and piece == 'structure') else piece


def materials(palette):
    """material name -> (rgba, specular, shininess)"""
    return {f'raft_{key}': (rgba(color(palette, part)), *SHINE[key]) for key, part in PIECE_COLOR.items()}


def identity(pose):
    return np.allclose(pose['pos'], 0) and np.allclose(pose['quat'], [1, 0, 0, 0])


# ---------------------------------------------------------------- MuJoCo
def write_mjcf(ref, parts, mats, release):
    act = ref['actuation']
    links = {link['name']: link for link in ref['links']}
    joints = ref['joints']
    child_of = {j['parent']: j for j in joints if j['name'] != 'trigger_joint'}

    def at(pose):
        return f'pos="{fmt(pose["pos"])}" quat="{fmt(pose["quat"])}"'

    def inertial(link):
        i = link['inertia']
        return (f'<inertial pos="{fmt(link["com"])}" mass="{link["mass"]:.6g}" fullinertia="{i["ixx"]:.6g} '
                f'{i["iyy"]:.6g} {i["izz"]:.6g} {i["ixy"]:.6g} {i["ixz"]:.6g} {i["iyz"]:.6g}"/>')

    def geoms(ind, name):
        pose = links[name]['mesh']['origin']
        where = '' if identity(pose) else ' '+at(pose)
        return ([f'{ind}<geom class="visual" mesh="{name}_{p}" material="raft_{piece_key(name, p)}"{where}/>'
                 for p in parts[name]['parts']] + [f'{ind}<geom class="collision" mesh="{name}"{where}/>'])
    sites = {ref['j2_spring']['anchor']['body']: ('j2_spring_anchor', ref['j2_spring']['anchor']['pos']),
             ref['j2_spring']['pin']['body']: ('j2_spring_pin', ref['j2_spring']['pin']['pos'])}
    x = ['<mujoco model="raft">',
         f'  <!-- Source Robotics RAFT teleoperation leader arm, robot_descriptions {release}. GENERATED by',
         '       tools/build_raft.py from source/raft (RAFT\'s model reference) and source/appearance/colors.json; do',
         '       not hand-edit. Body i frame = DH frame i-1, joint i turns about its z axis; qpos = 0 is the standby',
         '       pose (PAR6\'s standby pose). Actuators take joint torque in Nm (the servos run in current mode).',
         '       Joint friction, damping and armature are estimates (docs/ACTUATION.md). -->',
         '  <compiler angle="radian" meshdir="assets" autolimits="true" inertiafromgeom="false"/>',
         '  <option timestep="0.001" integrator="implicitfast"/>',
         '  <default>', '    <default class="raft">',
         f'      <joint axis="0 0 1" armature="{act["armature"]:g}" frictionloss="{act["frictionloss"]:g}" damping="{act["damping"]:g}"/>',
         f'      <motor ctrlrange="{-act["stall_torque_nm"]:.4f} {act["stall_torque_nm"]:.4f}"/>',
         '      <site group="3" size="0.004" rgba="0.9 0.2 0.1 1"/>',
         '      <default class="visual">', '        <geom type="mesh" contype="0" conaffinity="0" group="2"/>', '      </default>',
         '      <default class="collision">', '        <geom type="mesh" group="3"/>', '      </default>',
         '    </default>', '  </default>', '  <asset>']
    x += [f'    <material name="{n}" rgba="{fmt(c)}" specular="{s:g}" shininess="{h:g}"/>' for n, (c, s, h) in mats.items()]
    for name in links:
        x.append(f'    <mesh name="{name}" file="{name}.stl"/>')
        x += [f'    <mesh name="{name}_{p}" file="{info["file"]}"/>' for p, info in parts[name]['parts'].items()]
    x += ['  </asset>', '  <worldbody>', '    <body name="base_link" childclass="raft">',
          f'      {inertial(links["base_link"])}'] + geoms('      ', 'base_link')
    ind, name, depth = '      ', 'base_link', 0
    while name in child_of:
        joint = child_of[name]; name = joint['child']; depth += 1
        x += [f'{ind}<body name="{name}" {at(joint["origin"])}>', f'{ind}  {inertial(links[name])}',
              f'{ind}  <joint name="{joint["name"]}" range="{fmt(joint["range"])}"/>']
        ind += '  '
        x += geoms(ind, name)
        if name in sites:
            x.append(f'{ind}<site name="{sites[name][0]}" pos="{fmt(sites[name][1])}"/>')
    trigger = next(j for j in joints if j['name'] == 'trigger_joint')
    assert name == ref['tcp']['parent'] == trigger['parent']
    x += [f'{ind}<site name="tcp" {at(ref["tcp"]["origin"])}/>', f'{ind}<body name="trigger_link" {at(trigger["origin"])}>',
          f'{ind}  {inertial(links["trigger_link"])}', f'{ind}  <joint name="trigger_joint" range="{fmt(trigger["range"])}"/>']
    x += geoms(ind+'  ', 'trigger_link') + [f'{ind}</body>']
    for _ in range(depth):
        ind = ind[:-2]; x.append(f'{ind}</body>')
    x += ['    </body>', '  </worldbody>',
          '  <!-- the convex hulls of these pairs overlap where the real parts do not (the J1 bearing, the wrist at some J5 angles) -->',
          '  <contact>'] + [f'    <exclude body1="{a}" body2="{b}"/>' for a, b in ref['contact_excludes']] + ['  </contact>',
          '  <tendon>',
          '    <!-- optional J2 counterbalance (zero-length cable spring); stiffness = spring rate in N/m, 0 = not fitted -->',
          '    <spatial name="j2_spring" stiffness="0" springlength="0 0" width="0.0012" rgba="0.95 0.75 0.1 1" group="3">',
          '      <site site="j2_spring_anchor"/>', '      <site site="j2_spring_pin"/>', '    </spatial>', '  </tendon>',
          '  <actuator>']
    x += [f'    <motor name="{j["name"].replace("_joint", "_actuator")}" joint="{j["name"]}" class="raft"/>' for j in joints]
    x += ['  </actuator>', '  <sensor>', '    <framepos name="tcp_pos" objtype="site" objname="tcp"/>',
          '    <framequat name="tcp_quat" objtype="site" objname="tcp"/>', '  </sensor>', '  <keyframe>']
    x += [f'    <key name="{k["name"]}" qpos="{fmt(k["qpos"])}"/>' for k in ref['keyframes']] + ['  </keyframe>', '</mujoco>']
    (MUJOCO/'raft.xml').write_text('\n'.join(x)+'\n', encoding='utf-8')
    (MUJOCO/'scene.xml').write_text('\n'.join([
        '<mujoco model="RAFT scene">',
        '  <include file="raft.xml"/>',
        '  <!-- the PAR6 / PAROL6 viewer scene, its floor squares scaled with RAFT\'s 5/9 size -->',
        '  <statistic center="0.08 0 0.11" extent="0.3"/>',
        '  <visual>',
        '    <headlight diffuse="0.6 0.6 0.6" ambient="0.3 0.3 0.3" specular="0 0 0"/>',
        '    <rgba haze="0.15 0.25 0.35 1"/>',
        '    <global azimuth="120" elevation="-20" offwidth="1280" offheight="960"/>',
        '  </visual>',
        '  <asset>',
        '    <texture type="skybox" builtin="gradient" rgb1="0.3 0.5 0.7" rgb2="0 0 0" width="512" height="3072"/>',
        '    <texture type="2d" name="groundplane" builtin="checker" mark="edge" rgb1="0.2 0.3 0.4" rgb2="0.1 0.2 0.3"',
        '      markrgb="0.8 0.8 0.8" width="300" height="300"/>',
        '    <material name="groundplane" texture="groundplane" texuniform="true" texrepeat="9 9" reflectance="0.2"/>',
        '  </asset>',
        '  <worldbody>',
        '    <light pos="0 0 1.5" dir="0 0 -1" directional="true"/>',
        '    <geom name="floor" size="0 0 0.05" type="plane" material="groundplane"/>',
        '  </worldbody>',
        '</mujoco>'])+'\n', encoding='utf-8')


# ---------------------------------------------------------------- URDF
def write_urdf(ref, parts, mats):
    act = ref['actuation']

    def origin(pose):
        return f'<origin xyz="{fmt(pose["pos"])}" rpy="{fmt(pose["rpy"])}"/>'
    x = ['<?xml version="1.0" encoding="utf-8"?>', '<robot name="raft">']
    for link in ref['links']:
        name, i, mesh = link['name'], link['inertia'], link['mesh']['origin']
        x += [f'  <link name="{name}">', '    <inertial>', f'      <origin xyz="{fmt(link["com"])}" rpy="0 0 0"/>',
              f'      <mass value="{link["mass"]:.6g}"/>',
              f'      <inertia ixx="{i["ixx"]:.6g}" ixy="{i["ixy"]:.6g}" ixz="{i["ixz"]:.6g}" iyy="{i["iyy"]:.6g}" iyz="{i["iyz"]:.6g}" izz="{i["izz"]:.6g}"/>',
              '    </inertial>']
        for piece, info in parts[name]['parts'].items():
            material = f'raft_{piece_key(name, piece)}'
            x += [f'    <visual name="{name}_{piece}">', f'      {origin(mesh)}',
                  f'      <geometry><mesh filename="meshes/{info["file"]}"/></geometry>',
                  f'      <material name="{material}"><color rgba="{fmt(mats[material][0])}"/></material>', '    </visual>']
        x += [f'    <collision name="{name}_collision">', f'      {origin(mesh)}',
              f'      <geometry><mesh filename="meshes/{name}.stl"/></geometry>', '    </collision>', '  </link>']
    x += ['  <link name="tcp"/>']
    for joint in ref['joints']:
        lo, hi = joint['range']
        x += [f'  <joint name="{joint["name"]}" type="revolute">', f'    {origin(joint["origin"])}',
              f'    <parent link="{joint["parent"]}"/>', f'    <child link="{joint["child"]}"/>',
              f'    <axis xyz="{fmt(joint["axis"])}"/>',
              f'    <limit lower="{lo:.12g}" upper="{hi:.12g}" effort="{act["stall_torque_nm"]:.6g}" velocity="{act["speed_rad_s"]:.6g}"/>',
              f'    <dynamics damping="{act["damping"]:.6g}" friction="{act["frictionloss"]:.6g}"/>', '  </joint>']
    x += ['  <joint name="tcp_fixed_joint" type="fixed">', f'    {origin(ref["tcp"]["origin"])}',
          f'    <parent link="{ref["tcp"]["parent"]}"/>', '    <child link="tcp"/>', '  </joint>', '</robot>']
    (URDF/'raft.urdf').write_text('\n'.join(x)+'\n', encoding='utf-8')
    (URDF/'config/joint_names.yaml').write_text(
        'controller_joint_names:\n'+''.join(f'  - {j["name"]}\n' for j in ref['joints'][:6]), encoding='utf-8')
    (URDF/'launch/display.launch').write_text('''<?xml version='1.0' encoding='utf-8'?>
<launch>
  <param name="robot_description" textfile="$(find raft_description)/raft.urdf" />
  <node pkg="joint_state_publisher_gui" type="joint_state_publisher_gui" name="joint_state_publisher_gui" />
  <node pkg="robot_state_publisher" type="robot_state_publisher" name="robot_state_publisher" />
  <node pkg="rviz" type="rviz" name="rviz" />
</launch>
''', encoding='utf-8')
    (URDF/'package.xml').write_text(f'''<?xml version='1.0' encoding='utf-8'?>
<package format="3">
  <name>raft_description</name>
  <version>{version()}</version>
  <description>Source Robotics RAFT teleoperation leader arm: PAR6's kinematics at 5/9 scale, six joints and a trigger.</description>
  <maintainer email="petar@source-robotics.com">Source Robotics</maintainer>
  <license>CC-BY-4.0</license>
  <license>Apache-2.0</license>
</package>
''', encoding='utf-8')


# ---------------------------------------------------------------- documents, previews, index
def tables(ref):
    deg = np.rad2deg
    dh, joints = ref['dh'], ref['joints']
    rows = ['| Joint | d (mm) | a (mm) | alpha | theta offset |', '|---|---:|---:|---:|---:|']
    rows += [f'| `{joints[i]["name"]}` | {dh["d"][i]*1e3:.3f} | {dh["a"][i]*1e3:.3f} | {deg(dh["alpha"][i]):.0f} deg | '
             f'{deg(dh["theta_offset"][i]):.0f} deg |' for i in range(6)]
    raft_mm = {'a2': dh['a'][0], 'a3': dh['a'][1], 'a4': -dh['a'][2], 'a5': -dh['d'][3], 'a6 (TCP)': -dh['d'][5]}
    scale = ['| Length | RAFT (mm) | PAR6 (mm) | RAFT / PAR6 |', '|---|---:|---:|---:|']
    scale += [f'| {n} | {raft_mm[n]*1e3:.3f} | {p:g} | {raft_mm[n]*1e3/p:.4f} |' for n, p in PAR6_MM.items()]
    limits = ['| Joint | Lower | Upper | Where the numbers come from |', '|---|---:|---:|---|']
    limits += [f'| `{j["name"]}` | {j["range_deg"][0]:.2f} deg | {j["range_deg"][1]:.2f} deg | {j["range_source"]} |' for j in joints]
    keys = ['| Keyframe | qpos (deg), base_joint to trigger_joint |', '|---|---|']
    keys += [f'| `{k["name"]}` | {", ".join(f"{x:.0f}" for x in deg(k["qpos"]))} |' for k in ref['keyframes']]
    mass = ['| Link | Mass (g) | COM in the link frame (mm) |', '|---|---:|---|']
    mass += [f'| `{link["name"]}` | {link["mass"]*1e3:.2f} | {", ".join(f"{x*1e3:.2f}" for x in link["com"])} |' for link in ref['links']]
    total = sum(link['mass'] for link in ref['links'])
    mass.append(f'| total | {total*1e3:.2f} | |')
    act = ref['actuation']
    actuators = ['| Actuator | Joint | ctrlrange (Nm) |', '|---|---|---|']
    actuators += [f'| `{j["name"].replace("_joint", "_actuator")}` | `{j["name"]}` | +-{act["stall_torque_nm"]:.4f} |' for j in joints]
    moving = total-next(link['mass'] for link in ref['links'] if link['name'] == 'base_link')
    return {'VERSION': version(), 'DH_TABLE': '\n'.join(rows), 'SCALE_TABLE': '\n'.join(scale),
            'LIMITS_TABLE': '\n'.join(limits), 'KEYS_TABLE': '\n'.join(keys), 'MASS_TABLE': '\n'.join(mass),
            'ACTUATOR_TABLE': '\n'.join(actuators), 'SPEED': f'{act["speed_rad_s"]:g}', 'ARMATURE': f'{act["armature"]:g}',
            'FRICTION': f'{act["frictionloss"]:g}', 'DAMPING': f'{act["damping"]:g}',
            'MASS_TOTAL': f'{total*1e3:.1f}', 'MASS_MOVING': f'{moving*1e3:.1f}'}


def render(text, tokens, name):
    for key, value in tokens.items():
        text = text.replace('{{'+key+'}}', value)
    left = re.findall(r'\{\{[A-Z_]+\}\}', text)
    if left:
        raise ValueError(f'{name}: unknown tokens {left}')
    return text


def sim2bot(ref, urdf):
    joints = [j['name'] for j in ref['joints']]
    arm = joints[:6] if urdf else [j.replace('_joint', '_actuator') for j in joints[:6]]
    trigger = [joints[6]] if urdf else [joints[6].replace('_joint', '_actuator')]
    entry = 'raft.urdf' if urdf else 'scene.xml'
    data = {'version': 1, 'name': 'Source Robotics RAFT'+(' URDF' if urdf else ''), 'manufacturer': 'Source Robotics',
            'category': 'arm', 'license': 'CC-BY-4.0', 'sourceUrl': 'https://github.com/Source-Robotics/RAFT-teleoperation-arm',
            'packageVersion': version(), 'entry': entry, 'dof': 6, 'rootFrame': 'base_link', 'tcpSites': ['tcp'],
            'armActuators': arm, 'gripperActuators': trigger, 'endEffectorBodies': ['wrist_3_link'],
            'preview': 'previews/raft.png',
            'variants': [{'id': 'leader', 'label': 'RAFT leader arm', 'entry': entry, 'tcpSites': ['tcp'],
                          'endEffectorBodies': ['wrist_3_link'], 'gripperActuators': trigger, 'preview': 'previews/raft.png'}]}
    return json.dumps(data, indent=2)+'\n'


def build():
    ref, parts, palette = reference(), partitions(), load_palette()
    mats = materials(palette)
    tokens = tables(ref)
    for package, meshdir, kind in [(MUJOCO, 'assets', 'mujoco'), (URDF, 'meshes', 'urdf')]:
        if package.exists():
            shutil.rmtree(package)
        (package/meshdir/'visual').mkdir(parents=True)
        for link in ref['links']:
            shutil.copyfile(SOURCE/'meshes'/f'{link["name"]}.stl', package/meshdir/f'{link["name"]}.stl')
            for info in parts[link['name']]['parts'].values():
                shutil.copyfile(SOURCE/info['file'], package/meshdir/info['file'])
        (package/'docs').mkdir(); (package/'previews').mkdir()
        for path in sorted((SOURCE/'docs').glob('*.md')):
            (package/'docs'/path.name).write_text(render(path.read_text(encoding='utf-8'), tokens, path.name), encoding='utf-8')
        for path in sorted((SOURCE/'previews').glob('*.png')):
            shutil.copyfile(path, package/'previews'/path.name)
        front = (SOURCE/f'README.{kind}.md').read_text(encoding='utf-8')
        (package/'README.md').write_text(render(front, tokens, f'README.{kind}.md'), encoding='utf-8')
        (package/'sim2bot.robot.json').write_text(sim2bot(ref, kind == 'urdf'), encoding='utf-8')
    for directory in ['config', 'launch']:
        (URDF/directory).mkdir()
    write_mjcf(ref, parts, mats, version())
    write_urdf(ref, parts, mats)
    # the product guide's picture and the README's overview picture
    (ROOT/'docs/images/robots').mkdir(parents=True, exist_ok=True)
    shutil.copyfile(SOURCE/'previews/raft.png', ROOT/'docs/images/raft.png')
    shutil.copyfile(SOURCE/'previews/raft_isometric.png', ROOT/'docs/images/robots/raft_isometric.png')
    print(f'Built RAFT: mujoco/raft and urdf/raft_description ({len(ref["links"])} links, '
          f'{sum(len(p["parts"]) for p in parts.values())} coloured pieces).', flush=True)


if __name__ == '__main__':
    build()
